import { NextResponse } from "next/server";
import jwt from "jsonwebtoken";

export interface WhiteLabelSettingsRequest {
  companyName?: string;
  logo?: string;
  brandColor?: string;
  removeBranding?: boolean;
  contactEmail?: string;
  contactPhone?: string;
  contactWebsite?: string;
  footerText?: string;
  defaultReportTitle?: string;
}

const defaultSettings = {
  companyName: "SEOaudit Pro",
  logo: null,
  brandColor: "#1a365d",
  removeBranding: false,
  contactEmail: "support@example.com",
  contactPhone: null,
  contactWebsite: "https://example.com",
  footerText: "Generated by SEOaudit Pro",
  defaultReportTitle: "SEO Audit Report",
};

export async function GET(request: Request) {
  try {
    const authHeader = request.headers.get("authorization");
    if (!authHeader?.startsWith("Bearer ")) {
      return NextResponse.json(
        { error: "Authentication required" },
        { status: 401 }
      );
    }

    return NextResponse.json({
      success: true,
      settings: defaultSettings,
    });
  } catch (error) {
    console.error("Error fetching white label settings:", error);
    return NextResponse.json(
      { error: "Failed to fetch white label settings" },
      { status: 500 }
    );
  }
}

export async function POST(request: Request) {
  try {
    const authHeader = request.headers.get("authorization");
    if (!authHeader?.startsWith("Bearer ")) {
      return NextResponse.json(
        { error: "Authentication required" },
        { status: 401 }
      );
    }

    const body: WhiteLabelSettingsRequest = await request.json();

    return NextResponse.json({
      success: true,
      message: "White label settings saved successfully",
      settings: { ...defaultSettings, ...body },
    });
  } catch (error) {
    console.error("Error saving white label settings:", error);
    return NextResponse.json(
      { error: "Failed to save white label settings" },
      { status: 500 }
    );
  }
}

